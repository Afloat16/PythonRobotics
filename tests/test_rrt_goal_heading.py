"""Circular heading regressions for the car-like RRT planners."""

import math

import conftest  # Add root path to sys.path
import pytest

from PathPlanning.ClosedLoopRRTStar import closed_loop_rrt_star_car
from PathPlanning.RRTDubins import rrt_dubins
from PathPlanning.RRTStarDubins import rrt_star_dubins
from PathPlanning.RRTStarReedsShepp import rrt_star_reeds_shepp
from utils.angle import angle_mod


PLANNERS = [
    rrt_dubins.RRTDubins,
    rrt_star_dubins.RRTStarDubins,
    rrt_star_reeds_shepp.RRTStarReedsShepp,
    closed_loop_rrt_star_car.ClosedLoopRRTStar,
]


@pytest.mark.parametrize("planner_type", PLANNERS)
@pytest.mark.parametrize("goal_yaw, node_yaw, accepted", [
    (math.pi, -math.pi, True),
    (math.pi - 0.002, -math.pi + 0.002, True),
    (-math.pi + 0.002, math.pi - 0.002, True),
    (0.2 + 2 * math.pi, 0.2, True),
    (0.2 - 4 * math.pi, 0.2, True),
    (0.2, 0.2 + math.radians(0.25), True),
    (0.2, 0.2 + math.pi, False),
    (0.2, 0.2 + math.radians(5.0), False),
])
def test_goal_selection_uses_circular_heading(
        planner_type, goal_yaw, node_yaw, accepted):
    planner = planner_type([-2.0, 0.0, 0.0], [2.0, 0.0, goal_yaw],
                           [], [-3.0, 3.0], max_iter=1)
    node = planner.steer(planner.start, planner.Node(2.0, 0.0, node_yaw))
    assert node is not None
    planner.node_list = [planner.start, node]

    if isinstance(planner, closed_loop_rrt_star_car.ClosedLoopRRTStar):
        assert planner.get_goal_indexes() == ([1] if accepted else [])
    else:
        assert planner.search_best_goal_node() == (1 if accepted else None)


@pytest.mark.parametrize("goal_yaw", [math.pi, 0.2 + 2 * math.pi])
def test_reeds_shepp_planning_reaches_equivalent_goal(goal_yaw, monkeypatch):
    planner = rrt_star_reeds_shepp.RRTStarReedsShepp(
        [-2.0, 0.0, 0.0], [2.0, 0.0, goal_yaw], [], [-3.0, 3.0],
        max_iter=1)
    sample = planner.Node(2.0, 0.0, angle_mod(goal_yaw))
    monkeypatch.setattr(planner, "get_random_node", lambda: sample)

    path = planner.planning(animation=False)

    assert path is not None
    goal_node = planner.node_list[planner.search_best_goal_node()]
    assert goal_node.parent is planner.start
    assert math.hypot(goal_node.x - 2.0, goal_node.y) < 1e-10
    assert abs(angle_mod(goal_node.yaw - goal_yaw)) < 1e-10
    assert len(path) > 2
    for first, second in zip(path, path[1:]):
        assert math.dist(first[:2], second[:2]) <= planner.step_size + 1e-10


@pytest.mark.parametrize("goal_yaw, accepted", [
    (2 * math.pi, True), (-4 * math.pi, True), (math.pi, False),
])
def test_closed_loop_tracking_goal_heading(goal_yaw, accepted, monkeypatch):
    monkeypatch.setattr(closed_loop_rrt_star_car.pure_pursuit,
                        "animation", False)
    planner = closed_loop_rrt_star_car.ClosedLoopRRTStar(
        [0.0, 0.0, 0.0], [4.0, 0.0, 0.0], [], [-5.0, 5.0])
    # The tracker consumes a goal-to-start course, as generated by the planner.
    path = [[index / 10, 0.0, 0.0] for index in range(40, -1, -1)]
    feasible, x, y, yaw, v, t, a, d = planner.check_tracking_path_is_feasible(path)
    assert feasible

    # Replay the native controller's measured trajectory to isolate the final
    # heading check from the controller's separate reference-heading handling.
    prediction = (t, x, y, yaw, v, a, d, True)
    monkeypatch.setattr(closed_loop_rrt_star_car.pure_pursuit,
                        "closed_loop_prediction", lambda *args: prediction)
    path[0][2] = goal_yaw
    result, *_ = planner.check_tracking_path_is_feasible(path)
    assert result == accepted


